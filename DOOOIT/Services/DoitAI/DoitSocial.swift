/// 두잇 AI 사회·역사 엔진 (외부 AI·API 없이 직접 만든 자료)
/// - 한국사·세계사 연표: 언제, 누가, 그해에 무슨 일, 시대 순서, 역대 대통령, 조선 왕 순서
/// - 세계 여러 나라의 수도
/// - 통합사회·정치·경제·지리 핵심 개념
enum DoitSocial {
    static func answer(_ question: String) -> String? {
        let text = question.trimmingCharacters(in: .whitespacesAndNewlines)
        guard text.count >= 2, !isAppCommand(text) else { return nil }
        if let reply = orderList(text) { return reply }
        if let reply = capital(text) { return reply }
        if let reply = concept(text) { return reply }
        if let reply = event(text) { return reply }
        if let reply = yearEvents(text) { return reply }
        return nil
    }

    // MARK: - 퀴즈

    /// 짧은 답 퀴즈 하나 (topic 예: "수도", "한국사", "세계사", "임진왜란", "경제")
    static func quiz(topic: String?) -> DoitQuizItem? {
        let t = topic.map(norm) ?? ""
        if !t.isEmpty {
            if t.contains("수도") || t.contains("나라") || t.contains("지리") { return capitalQuiz() }
            if t.contains("세계사") { return eventQuiz(events.filter { $0.world && !$0.approx }.randomElement()) }
            if let match = bestEvent(in: t) { return eventQuiz(match) }
            if let item = concepts.first(where: { $0.names.contains { norm($0).count >= 2 && (t.contains(norm($0)) || norm($0).contains(t)) } }) {
                return conceptQuiz(item)
            }
            if t.contains("한국사") || t.contains("역사") || t.contains("연도") || t.contains("국사") {
                return eventQuiz(events.filter { !$0.world && !$0.approx }.randomElement())
            }
            if t.contains("경제") || t.contains("정치") || t.contains("사회") || t.contains("법") {
                return concepts.filter(isQuizable).randomElement().flatMap(conceptQuiz)
            }
        }
        switch Int.random(in: 0..<3) {
        case 0: return capitalQuiz()
        case 1: return eventQuiz(events.filter { !$0.approx }.randomElement())
        default: return concepts.filter(isQuizable).randomElement().flatMap(conceptQuiz)
        }
    }

    private static func capitalQuiz() -> DoitQuizItem? {
        guard let country = countries.randomElement() else { return nil }
        return DoitQuizItem(question: "\(country.names[0])의 수도는 어디일까요?", answers: [country.capital] + country.capitalAliases,
                            explanation: "\(country.names[0])의 수도: \(country.capital) (\(country.continent))" + (country.note.map { "\n\($0)" } ?? ""))
    }

    private static func eventQuiz(_ event: SocEvent?) -> DoitQuizItem? {
        guard let event else { return nil }
        let name = event.names[0]
        var answers = ["\(event.year < 0 ? "기원전" : "")\(abs(event.year))년", "\(event.year < 0 ? "기원전" : "")\(abs(event.year))"]
        if event.year < 0 { answers += ["bc\(abs(event.year))", "bc\(abs(event.year))년"] }
        return DoitQuizItem(question: "다음 사건은 몇 년에 일어났을까요?\n'\(name)' — \(event.text)", answers: answers,
                            explanation: "\(name): \(yearText(event))\n\(event.text)" + (event.who.map { "\n관련 인물: \($0)" } ?? ""))
    }

    /// 설명 첫 줄이 "산: …"처럼 여러 용어를 나눠 설명하면 퀴즈로 내지 않음
    private static func isQuizable(_ item: SocConcept) -> Bool {
        guard let line = item.body.components(separatedBy: "\n").first else { return false }
        return !line.prefix(14).contains(":") && line.count >= 15
    }

    private static func conceptQuiz(_ item: SocConcept) -> DoitQuizItem? {
        guard var line = item.body.components(separatedBy: "\n").first else { return nil }
        for name in item.names.sorted(by: { $0.count > $1.count }) { line = line.replacingOccurrences(of: name, with: "(   )") }
        return DoitQuizItem(question: "다음 설명에 알맞은 용어는 무엇일까요?\n\(line)", answers: item.names,
                            explanation: "정답: \(item.names[0])\n\(item.body)")
    }

    // MARK: - 공통

    private static func isAppCommand(_ text: String) -> Bool {
        let words = ["추가해", "추가", "타이머", "일정", "플랜", "삭제", "지워", "메모", "알람", "예약", "완료했", "단어장",
                     "할 일", "할일", "디데이", "d-day", "D-Day", "문제 내", "퀴즈", "스톱워치", "고려해"]
        return words.contains { text.contains($0) }
    }

    private static func norm(_ s: String) -> String {
        s.lowercased().filter { !" ·・.-_\t\n'\"?!~,「」『』".contains($0) }
    }

    private static func hasBatchim(_ word: String) -> Bool {
        guard let last = word.trimmingCharacters(in: .whitespaces).last else { return false }
        if let scalar = last.unicodeScalars.first, (0xAC00...0xD7A3).contains(scalar.value) {
            return (scalar.value - 0xAC00) % 28 != 0
        }
        if last.isNumber { return "013678".contains(last) }
        return false
    }

    /// josa("서울", "이에요", "예요") → "이에요"
    private static func josa(_ word: String, _ withBatchim: String, _ without: String) -> String {
        hasBatchim(word) ? withBatchim : without
    }

