    private static func capital(_ text: String) -> String? {
        let compact = norm(text)
        let reverse = ["어느 나라", "어디 나라", "무슨 나라", "어떤 나라", "어느나라", "무슨나라", "어떤나라"].contains(where: text.contains)
        guard compact.contains("수도") || reverse else { return nil }
        if reverse {
            var best: (SocCountry, String, Int)?
            for country in countries {
                for name in [country.capital] + country.capitalAliases {
                    let key = norm(name)
                    if key.count >= 2, compact.contains(key), latinSafe(key, text), key.count > (best?.2 ?? 0) { best = (country, name, key.count) }
                }
            }
            if let (country, name, _) = best {
                let countryName = country.names.count > 1 && country.names[1] != country.names[0] ? "\(country.names[0])(\(country.names[1]))" : country.names[0]
                return "**\(name)\(josa(name, "은", "는")) \(countryName)의 수도예요.**\n\(country.continent)에 있는 나라예요." + (country.note.map { "\n\($0)" } ?? "")
            }
        }
        var best: (SocCountry, Int)?
        for country in countries {
            for name in country.names {
                let key = norm(name)
                if compact.contains(key), latinSafe(key, text), key.count > (best?.1 ?? 0) { best = (country, key.count) }
            }
        }
        guard let country = best?.0, compact.contains("수도") else { return nil }
        let name = country.names[0]
        return "**\(name)의 수도는 \(country.capital)\(josa(country.capital, "이에요", "예요")).**\n\(country.continent)에 있는 나라예요."
            + (country.note.map { "\n\($0)" } ?? "")
    }

