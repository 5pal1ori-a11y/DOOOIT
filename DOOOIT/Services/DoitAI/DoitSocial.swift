    private static func orderList(_ text: String) -> String? {
        let compact = norm(text)
        let wantsOrder = ["순서", "흐름", "차례", "역대", "목록", "순으로", "나열", "정리"].contains(where: compact.contains)
        if compact.contains("대통령") {
            if let range = text.range(of: #"\d{1,2}\s*대\s*대통령"#, options: .regularExpression),
               let n = Int(text[range].prefix { $0.isNumber }) {
                guard let p = presidents.first(where: { term in
                    let numbers = term.term.replacingOccurrences(of: "대", with: "").split(separator: "~").compactMap { Int($0) }
                    return numbers.count == 2 ? (numbers[0]...numbers[1]).contains(n) : numbers.first == n
                }) else { return nil }
                return "**제\(n)대 대통령: \(p.name)**\n재임 \(p.years) (\(p.term))"
            }
            guard wantsOrder || compact.contains("역대") else { return nil }
            let lines = presidents.enumerated().map { "\($0.offset + 1). \($0.element.name) (\($0.element.term), \($0.element.years))" }
            return "**대한민국 역대 대통령**\n" + lines.joined(separator: "\n")
        }
        guard wantsOrder else { return nil }
        if compact.contains("조선") && (compact.contains("왕") || compact.contains("임금")) {
            return "**조선의 왕 27대**\n" + joseonKings.enumerated().map { "\($0.offset + 1). \($0.element)" }.joined(separator: " · ")
