    fileprivate struct SocEvent {
        let year: Int
        let end: Int?
        let approx: Bool
        let names: [String]
        let text: String
        let who: String?
        let world: Bool
    }

    private static func k(_ year: Int, _ names: [String], _ text: String, who: String? = nil, end: Int? = nil, approx: Bool = false) -> SocEvent {
        SocEvent(year: year, end: end, approx: approx, names: names, text: text, who: who, world: false)
    }

    private static func w(_ year: Int, _ names: [String], _ text: String, who: String? = nil, end: Int? = nil, approx: Bool = false) -> SocEvent {
        SocEvent(year: year, end: end, approx: approx, names: names, text: text, who: who, world: true)
    }

    private static func yearText(_ e: SocEvent) -> String {
        func one(_ y: Int) -> String { y < 0 ? "기원전 \(-y)년" : "\(y)년" }
        var text = one(e.year)
        if let end = e.end { text = (e.year < 0 && end < 0) ? "기원전 \(-e.year)~\(-end)년" : "\(one(e.year).dropLast())~\(one(end))" }
        if e.approx { text += "경" }
        return text
    }

