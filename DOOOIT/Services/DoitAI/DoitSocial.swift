    private static func bestEvent(in compact: String) -> SocEvent? {
        var best: (SocEvent, Int)?
        for e in events {
            for name in e.names {
                let key = norm(name)
                if key.count >= 2, compact.contains(key), key.count > (best?.1 ?? 0) { best = (e, key.count) }
            }
        }
        return best?.0
    }

    private static func event(_ text: String) -> String? {
        let compact = norm(text)
        guard let e = bestEvent(in: compact) else { return nil }
        guard historyCues.contains(where: text.contains) || compact.count <= 8 else { return nil }
        let name = e.names[0]
        if ["누가", "누구", "세운", "세웠", "인물", "주도", "이끈", "건국자"].contains(where: text.contains), let who = e.who {
            return "**\(name): \(who)**\n\(yearText(e)) · \(e.text)"
        }
        var lines = ["**\(name): \(yearText(e))**", e.text]
        if let who = e.who { lines.append("관련 인물: \(who)") }
        let sameYear = events.filter { $0.year == e.year && $0.names[0] != name }.prefix(3)
        if !sameYear.isEmpty { lines.append("같은 해: " + sameYear.map { $0.names[0] }.joined(separator: ", ")) }
        return lines.joined(separator: "\n")
    }

    private static func yearEvents(_ text: String) -> String? {
        guard ["무슨 일", "어떤 일", "사건", "일어난", "일어났", "있었", "뭐가", "무엇", "무슨일", "어떤일", "역사"].contains(where: text.contains) else { return nil }
        guard let range = text.range(of: #"(기원전\s*)?\d{1,4}\s*년"#, options: .regularExpression) else { return nil }
        let part = String(text[range])
        guard var year = Int(part.filter(\.isNumber)) else { return nil }
        if part.contains("기원전") { year = -year }
        let found = events.filter { $0.year == year || $0.end == year }
        guard !found.isEmpty else { return nil }
        var lines = ["**\(year < 0 ? "기원전 \(-year)" : "\(year)")년에 있었던 일**"]
        for e in found {
            lines.append("• \(e.world ? "세계" : "한국") · \(e.names[0]) (\(yearText(e))): \(e.text)")
        }
        return lines.joined(separator: "\n")
    }

