    /// "다음 중 파장이 가장 짧은 전자기파는?" — 선지가 모두 한 차례표에 있을 때
    static func scaleQuestion(_ p: Problem) -> Found? {
        guard p.isChoice, p.box.isEmpty, !p.negated else { return nil }
        let c = p.compact
        for scale in scales {
            func rank(_ choice: String) -> Int? {
                let k = key(choice)
                return scale.order.firstIndex { $0.contains { key($0) == k } }
            }
            let ranks = p.choices.map(rank)
            guard ranks.allSatisfy({ $0 != nil }) else { continue }
            let asks = scale.asks.filter { matches(c, $0.0) }
            guard asks.count == 1, let wantMax = asks.first?.1 else { continue }
            let values = ranks.compactMap { $0 }
            guard let target = wantMax ? values.max() : values.min() else { continue }
            let hits = values.indices.filter { values[$0] == target }
            guard hits.count == 1 else { return nil }
            let steps = [SolutionStep(hint: "차례", work: scale.order.map { $0[0] }.joined(separator: " < "))]
            return pick(p, index: hits[0], concept: scale.names[0], steps: steps)
        }
        return nil
    }
