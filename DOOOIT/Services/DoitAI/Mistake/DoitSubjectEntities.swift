    private static let negationWords = ["않", "없", "아니", "못하", "못한", "못했", "불가"]

    /// 문장 하나가 대상(entity)에 맞는지: true 맞음, false 틀림, nil 모름
    static func judgeEntity(_ sentence: String, table: EntityTable, entity: Int) -> Bool? {
        let s = sentence.filter { !$0.isWhitespace }
        guard s.count >= 1 else { return nil }
        var ownRanges: [NSRange] = [], otherRanges: [NSRange] = []
        let own = Set(table.entities[entity].traits)
        let ns = s as NSString
        for (i, e) in table.entities.enumerated() {
            for trait in e.traits {
                guard let regex = try? NSRegularExpression(pattern: trait) else { continue }
                let ms = regex.matches(in: s, range: NSRange(location: 0, length: ns.length)).map(\.range)
                guard !ms.isEmpty else { continue }
                if i == entity { ownRanges += ms } else if !own.contains(trait) { otherRanges += ms }
            }
        }
        let ownHit = !ownRanges.isEmpty, otherHit = !otherRanges.isEmpty
        guard ownHit != otherHit else { return nil }
        // 덮인 글자: 특징 꼴 · 표에 있는 이름. 남은 한글이 많으면 다른 내용이 섞인 문장이라 모름
        var covered = IndexSet()
        for r in ownRanges + otherRanges { covered.insert(integersIn: r.location..<(r.location + r.length)) }
        for e in table.entities { for name in e.names {
            let k = name.filter { !$0.isWhitespace } as NSString
            var from = 0
            while from < ns.length {
                let r = ns.range(of: k as String, range: NSRange(location: from, length: ns.length - from))
                guard r.location != NSNotFound else { break }
                covered.insert(integersIn: r.location..<(r.location + r.length)); from = r.location + max(1, r.length)
            }
        } }
        var leftover = ""
        for i in 0..<ns.length where !covered.contains(i) {
            if let scalar = Unicode.Scalar(ns.character(at: i)) { leftover.unicodeScalars.append(scalar) }
        }
        let hangulLeft = leftover.filter { DoitSubjectNote.isHangul($0) }
        // 끝맺는 말·조사는 세지 않아요
        let trimmed = hangulLeft.replacingOccurrences(of: #"(하였다|했다|하였음|하였으며|하였고|되었다|됐다|이었다|였다|이다|한다|된다|하다|되다|했음|함|됨|임|다|을|를|이|가|은|는|의|에|에서|으로|로|와|과|도|등|하여|해|하고|하며|시켰다|시키었다|세웠다|만들었다|두었다|주었다|있다|있었다|이루었다|이뤘다|사용하였다|사용했다|실시하였다|실시했다|설치하였다|설치했다|정비하였다|추진하였다|편찬하였다|펼쳤다|일어났다|나타난다|나타났다|강조하였다|강조했다|주장하였다|주장했다|중시하였다|썼다|지었다|저술하였다|남겼다|만든|만들|크게|모두|직접)"#,
                                                    with: "", options: .regularExpression)
        guard trimmed.count <= 6 else { return nil }
        // 부정어: 특징 꼴 밖에 '않·없·아니'가 있으면 뜻이 뒤집혀요 (맞는 특징 + 부정 → 틀림, 그 밖은 모름)
        let negated = negationWords.contains { leftover.contains($0) }
        if negated { return ownHit ? false : nil }
        return ownHit
    }

    /// 대상 하나에 대해 묻는 문제의 대상 (표, 대상)
    static func askedEntity(_ p: Problem) -> (table: Int, entity: Int)? {
        let stem = p.stem
        let c = p.compact
        guard !matches(c, #"(이후|이전|직전|직후|전에|후에|다음에|사이에|보다|공통점|차이점|비교)"#) else { return nil }
        let found = mentionedEntities(stem)
        guard found.count == 1, let one = found.first else { return nil }
        let entity = entityTables[one.table].entities[one.entity]
        // 이름 바로 뒤에 묻는 말
        let ok = entity.names.contains { name in
            let k = NSRegularExpression.escapedPattern(for: name.filter { !$0.isWhitespace })
            return matches(c, k + #"(왕|대왕)?(의|에대한|에관한|에서|과관련|와관련|이|가|은|는|때|대|시기|시대)"#)
        }
        guard ok, matches(c, #"(설명|업적|정책|사실|특징|주장|사상|기능|모습|활동|작품|저서|내용|관련|생활|해당|대한|때|성질|역할|표준화석|번성)"#) else { return nil }
        return one
    }

    /// "○○에 대한 설명으로 옳은(옳지 않은) 것은?" · "○○의 작품은?" · "○○의 표준 화석은?"
    static func entityStatements(_ p: Problem) -> Found? {
        guard p.isChoice, p.box.isEmpty, let asked = askedEntity(p) else { return nil }
        let table = entityTables[asked.table]
        var verdicts: [Bool] = []
        for choice in p.choices {
            guard let v = judgeEntity(choice, table: table, entity: asked.entity) else { return nil }
            verdicts.append(v)
        }
        let hits = verdicts.indices.filter { verdicts[$0] != p.negated }
        guard hits.count == 1 else { return nil }
        let name = table.entities[asked.entity].names[0]
        let steps = p.choices.indices.map { SolutionStep(hint: "", work: "\(circled($0 + 1)) \(p.choices[$0]) → \(verdicts[$0] ? "맞아요" : "\(name)와(과) 관계없어요")") }
        return pick(p, index: hits[0], concept: name, steps: steps)
    }

    /// 설명 → 대상: "다음 업적을 남긴 왕은?", "삼엽충이 번성한 지질 시대는?"
    static func entityFromDescription(_ p: Problem) -> Found? {
        guard !p.negated, p.box.isEmpty else { return nil }
        let c = p.compact
        guard !matches(c, #"(이후|이전|직전|직후|전에|후에|사이에|보다|공통점|차이점|옳은|옳지|아닌|설명으로|연결|짝)"#) else { return nil }
        guard matches(c, #"(은|는|인가|무엇|누구|고르면|것은)\??$"#) else { return nil }
        for table in entityTables {
            // 표의 특징 중 문제 글에 나온 것
            var matched: [String] = []
            for e in table.entities { for t in e.traits where matches(c, t) && !matched.contains(t) { matched.append(t) } }
            guard !matched.isEmpty else { continue }
            // 나온 특징을 모두 가진 대상
            let owners = table.entities.indices.filter { i in matched.allSatisfy { table.entities[i].traits.contains($0) } }
            if p.isChoice {
                let named = p.choices.map { entityNamed($0, table: table) }
                guard named.allSatisfy({ $0 != nil }) else { continue }
                let hits = named.indices.filter { owners.contains(named[$0]!) }
                // 선지 대상 중 문제 특징을 하나라도 가진 대상이 답 하나뿐이어야
                let touched = named.indices.filter { i in matched.contains { table.entities[named[i]!].traits.contains($0) } }
                guard hits.count == 1, touched == hits else { return nil }
                let e = table.entities[named[hits[0]]!]
                return pick(p, index: hits[0], concept: e.names[0], steps: [SolutionStep(hint: "단서", work: "문제의 설명은 \(e.names[0])에 해당해요.")])
            }
            guard owners.count == 1, table.kinds.contains(where: { c.contains($0) }) else { continue }
            let e = table.entities[owners[0]]
            return Found(answer: e.names[0], concept: e.names[0], steps: [SolutionStep(hint: "단서", work: "문제의 설명은 \(e.names[0])에 해당해요.")])
        }
        return nil
    }

    /// "○○ - □□" 짝 하나 판단 (한쪽이 대상 이름, 다른 쪽이 특징)
    static func judgePair(_ choice: String) -> (verdict: Bool, why: String)? {
        let parts = choice.components(separatedBy: CharacterSet(charactersIn: "-–—:")).map { $0.trimmingCharacters(in: .whitespaces) }.filter { !$0.isEmpty }
        guard parts.count == 2 else { return nil }
        var results: [Bool] = []
        var why = ""
        for table in entityTables {
            for (nameSide, otherSide) in [(parts[0], parts[1]), (parts[1], parts[0])] {
                guard let ei = entityNamed(nameSide, table: table) else { continue }
                // 다른 쪽도 같은 표의 대상 이름이면 짝 문제가 아님
                if entityNamed(otherSide, table: table) != nil { continue }
                if let v = judgeEntity(otherSide, table: table, entity: ei) {
                    results.append(v)
                    why = v ? "\(table.entities[ei].names[0]): \(otherSide) ✓" : "\(otherSide)은(는) \(table.entities[ei].names[0])와(과) 관계없어요"
                }
            }
        }
        guard let first = results.first, results.allSatisfy({ $0 == first }) else { return nil }
        return (first, why)
    }

    static func entityPairs(_ p: Problem) -> Found? {
        guard p.isChoice, matches(p.compact, #"(연결|짝지|짝을|짝이|짝은)"#),
              p.choices.allSatisfy({ $0.contains("-") || $0.contains("–") || $0.contains("—") || $0.contains(":") }) else { return nil }
        var verdicts: [Bool] = []
        var steps: [SolutionStep] = []
        for (i, choice) in p.choices.enumerated() {
            guard let r = judgePair(choice) else { return nil }
            verdicts.append(r.verdict)
            steps.append(SolutionStep(hint: "", work: "\(circled(i + 1)) \(r.why)"))
        }
        let hits = verdicts.indices.filter { verdicts[$0] != p.negated }
        guard hits.count == 1 else { return nil }
        return pick(p, index: hits[0], concept: "바르게 연결하기", steps: steps)
    }

    /// <보기> 항목 판단: 문제가 묻는 대상의 사실표로
    static func entityVerdict(_ item: String, stem: String) -> Bool? {
        let p = Problem(full: stem, body: stem, choices: [], box: [])
        guard let asked = askedEntity(p) else { return nil }
        return judgeEntity(item, table: entityTables[asked.table], entity: asked.entity)
    }

