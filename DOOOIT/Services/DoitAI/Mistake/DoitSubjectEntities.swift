    /// 글에 나온 대상 (표, 대상 번호). 다른 대상과 이름이 같으면 함께 나온 말(고려·조선)로 가려요
    static func mentionedEntities(_ text: String, in tables: [EntityTable] = entityTables) -> [(table: Int, entity: Int)] {
        var out: [(Int, Int)] = []
        for (ti, table) in tables.enumerated() {
            for (ei, entity) in table.entities.enumerated() {
                guard entity.names.contains(where: { nameAppears($0, in: text) }) else { continue }
                // 이름이 같은 대상이 있으면 꾸밈말이 있어야
                let same = table.entities.indices.filter { $0 != ei && !Set(table.entities[$0].names).isDisjoint(with: entity.names) }
                if !same.isEmpty {
                    guard let q = entity.qualifier, text.contains(q), !same.contains(where: { table.entities[$0].qualifier.map(text.contains) ?? false }) else { continue }
                }
                out.append((ti, ei))
            }
        }
        // 짧은 이름이 긴 이름 속에 든 것 빼기 ("이이"·"이익" 속 "이" 같은 것은 없지만 "성왕" ⊂ "진성 여왕" 같은 것)
        return out.filter { item in
            let names = tables[item.0].entities[item.1].names
            return !out.contains { other in
                (other.0 != item.0 || other.1 != item.1) && tables[other.0].entities[other.1].names.contains { long in
                    names.contains { short in long.count > short.count && long.filter { !$0.isWhitespace }.contains(short.filter { !$0.isWhitespace }) && nameAppears(long, in: text) }
                }
            }
        }
    }

    /// 이름이 낱말로 나오는지 (앞은 한글이 아니고, 뒤는 조사뿐)
    static func nameAppears(_ name: String, in text: String) -> Bool {
        let variants = Set([name, name.filter { !$0.isWhitespace }])
        let particles = "(?:때|대|의|은|는|이|가|을|를|와|과|에|에게|에서|으로|로|이다|이며|이고|도|만|께서|시대|왕)*"
        for v in variants where !v.isEmpty {
            let pattern = #"(?<![가-힣A-Za-z])"# + NSRegularExpression.escapedPattern(for: v) + #"(?="# + particles + #"(?![가-힣]))"#
            if matches(text, pattern) { return true }
        }
        return false
    }

    /// 선지(짧은 글)가 대상 이름 그 자체이면 그 대상
    static func entityNamed(_ choice: String, table: EntityTable) -> Int? {
        let k = key(choice)
        let hits = table.entities.indices.filter { table.entities[$0].names.contains { key($0) == k } }
        return hits.count == 1 ? hits[0] : nil
    }

