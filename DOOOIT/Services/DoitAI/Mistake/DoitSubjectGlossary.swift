        let t = text.trimmingCharacters(in: .whitespacesAndNewlines)
        guard t.count >= 8, t.count <= 120, !t.contains("\n"), matches(t, #"(\?|은$|는$|뭐야|뭐지|무엇|누구|이름)"#) else { return nil }
        let p = Problem(full: t, body: t, choices: [], box: [])
        guard let found = glossaryAnswer(p) ?? entityFromDescription(p) else { return nil }
        let why = found.steps.first(where: { $0.hint != "답" })?.work ?? ""
        return "**\(found.answer)**" + (why.isEmpty ? "" : "\n\(why)")
    }

    /// 용어 사전으로 답하기
    static func glossaryAnswer(_ p: Problem) -> Found? {
        guard p.box.isEmpty else { return nil }
        let c = p.compact
        guard !matches(c, #"(옳지않|설명으로|순서|나열|보기|모두고르|있는대로|공통점|차이점|반대(말|개념|되는|인것|현상|의뜻)|예로|예는|사례|아닌것)"#) else { return nil }
        // "~으로 옳은 것은?"은 선지가 짧은 말(용어)일 때만
        if matches(c, #"옳은것"#), !p.isChoice || p.choices.contains(where: { $0.count > 12 || $0.hasSuffix(".") }) { return nil }
        let hits = glossary.filter { gl in gl.all.allSatisfy { matches(c, $0) } && !gl.none.contains { matches(c, $0) } }
        guard let first = hits.first, Set(hits.map { key($0.answers[0]) }).count == 1 else { return nil }
        // 꼴 밖에 '아닌·않는' 같은 말이 남으면 뒤집힌 물음일 수 있어요
        let outside = first.all.reduce(c) { $0.replacingOccurrences(of: $1, with: "", options: .regularExpression) }
        guard !matches(outside, #"(아닌|않은|않는|틀린|잘못된|옳지않은|알맞지않은|바르지않은|적절하지않은|해당하지않는)것"#) else { return nil }
        // 해(연도)를 묻는데 답이 연도가 아니면 다른 것을 묻는 문제예요
        if matches(c, #"(해는|연도|년도|언제)"#), !first.answers.contains(where: { $0.contains("년") }) { return nil }
        let steps = [SolutionStep(hint: "개념", work: first.why)]
        if p.isChoice {
            guard let index = uniqueChoice(p, matching: first.answers) else { return nil }
            return pick(p, index: index, concept: first.answers[0], steps: steps)
        }
        return Found(answer: first.answers[0], concept: first.answers[0], steps: steps + [SolutionStep(hint: "답", work: first.answers[0])])
    }
}

