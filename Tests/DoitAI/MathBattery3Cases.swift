/// 한 문제 풀어 보기: 정답 / 못 풂 / 오답 (객관식은 선지 번호로)
func mathBattery3Grade(_ item: M3Case) -> (verdict: Int, answer: String) {
    let scan = DoitProblemScan.scan(item.text)
    let choices = scan.choices
    let isChoice = choices.count >= 2
    guard let solution = DoitAutoSolve.engine(text: item.text, choices: choices, isChoice: isChoice, body: scan.body) else { return (0, "") }
    let answer = solution.finalAnswer
    // 함정: 푼 답이 나오면 오답
    if item.answer.isEmpty { return (-1, answer) }
    if isChoice {
        if answer.hasPrefix("계산한 값") {
            let value = answer.replacingOccurrences(of: "계산한 값:", with: "").trimmingCharacters(in: .whitespaces)
            let n = Int(item.answer) ?? 0
            if choices.indices.contains(n - 1), batteryMatches(value, expected: choices[n - 1]) { return (0, answer) }
            return (-1, answer)
        }
        let right = DoitGrader.choiceNumber(answer, choices: choices).map { "\($0)" == item.answer } ?? false
        return (right ? 1 : -1, answer)
    }
    return (batteryMatches(answer, expected: item.answer) ? 1 : -1, answer)
}

func runMathBattery3Cases() {
    func run(_ cases: [M3Case], title: String) {
        var units: [String] = []
        var tally: [String: (c: Int, u: Int, w: Int, n: Int)] = [:]
        var wrong: [String] = [], unsolved: [String] = []
        for item in cases {
            if tally[item.unit] == nil { units.append(item.unit); tally[item.unit] = (0, 0, 0, 0) }
            let (verdict, answer) = mathBattery3Grade(item)
            let label = item.text.replacingOccurrences(of: "\n", with: " / ")
            var t = tally[item.unit]!
            t.n += 1
            switch verdict {
            case 1: t.c += 1
            case 0: t.u += 1; if !item.answer.isEmpty { unsolved.append("[\(item.unit)] " + label) }
            default:
                t.w += 1
                wrong.append("[\(item.unit)] \(label) → 엔진 답 '\(answer)', 정답 '\(item.answer.isEmpty ? "(풀면 안 됨)" : item.answer)'")
            }
            tally[item.unit] = t
            check("\(title) 오답 없음: \(label)", verdict >= 0, "엔진 답 '\(answer)', 정답 '\(item.answer.isEmpty ? "(풀면 안 됨)" : item.answer)'")
        }
        var total = (c: 0, u: 0, w: 0, n: 0)
        for unit in units {
            let t = tally[unit]!
            if unit.hasSuffix("함정") {
                print("\(title) [함정]: \(t.n)개 중 푼 것 \(t.w)개")
            } else {
                print("\(title) [\(unit)]: 정답 \(t.c) / \(t.n), 못 풂 \(t.u), 오답 \(t.w)")
                total = (total.c + t.c, total.u + t.u, total.w + t.w, total.n + t.n)
            }
        }
        print("\(title): 정답 \(total.c) / 전체 \(total.n), 못 풂 \(total.u), 오답 \(total.w)")
        for w in wrong { print("  ✗ 오답: " + w) }
        for u in unsolved { print("  · 못 풂: " + u) }
    }
    run(mathBattery3, title: "수학 배터리3")
    run(mathBattery3Dev, title: "수학 배터리3 개발2")
    run(mathBattery3Dev3, title: "수학 배터리3 개발3")
    if !mathBattery3Fresh.isEmpty { run(mathBattery3Fresh, title: "수학 배터리3 새 문제") }
}
