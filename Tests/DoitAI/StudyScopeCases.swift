    } else { check("제안: 공통수학1 피타고라스 → 중학교 단원", false, "\(DoitStudy.resolve(subject: "공통수학1", unit: "피타고라스"))") }

    // 5) 교육과정 범위: 중학교 수학 단원이 교과서 단원대로 있는지
    let middleMath = Set(DoitStudy.catalog.filter { $0.subjectName == "중학교 수학" }.map(\.unit))
    let expected = ["소인수분해", "정수와 유리수", "문자와 식", "좌표평면과 그래프", "기본 도형과 작도", "평면도형과 입체도형", "자료의 정리와 해석",
                    "유리수와 순환소수", "식의 계산", "일차부등식", "연립일차방정식", "일차함수와 그래프", "일차함수와 일차방정식의 관계",
                    "삼각형의 성질", "사각형의 성질", "도형의 닮음", "평행선과 선분의 길이의 비", "삼각형의 무게중심", "피타고라스 정리", "경우의 수와 확률",
                    "제곱근과 실수", "근호를 포함한 식의 계산", "다항식의 곱셈과 인수분해", "이차방정식", "이차함수와 그래프", "삼각비", "원의 성질", "대푯값과 산포도", "상관관계"]
    let missing = expected.filter { !middleMath.contains($0) }
    check("중학교 수학 교과서 단원 모두 있음", missing.isEmpty, "\(missing)")
    // 같은 학교급·과목 안에 같은 개념 이름이 두 단원에 있으면 검색이 모호해짐
    var owner: [String: String] = [:]
    var dupes: [String] = []
    for (subject, entries) in DoitCurriculum.bySubject {
        for entry in entries {
            for name in entry.names {
                let key = "\(subject)|\(entry.level.rawValue)|\(name.lowercased().filter { !$0.isWhitespace })"
                if let unit = owner[key], unit != entry.unit { dupes.append("\(subject) \(entry.level.rawValue) '\(name)': \(unit) / \(entry.unit)") }
                owner[key] = entry.unit
            }
        }
    }
    check("한 학교급·과목 안에서 개념 이름이 두 단원에 겹치지 않음", dupes.isEmpty, "\(dupes.count)개: " + dupes.prefix(15).joined(separator: " | "))
    let units = Set(DoitCurriculum.bySubject.flatMap { s in s.entries.map { "\(s.subject)|\($0.level.rawValue)|\($0.unit)" } })
    let small = units.filter { key in
        let parts = key.split(separator: "|").map(String.init)
        return (DoitCurriculum.bySubject.first { $0.subject == parts[0] }?.entries.filter { $0.level.rawValue == parts[1] && $0.unit == parts[2] }.count ?? 0) < 3
    }
    check("단원마다 개념이 3개 이상", small.isEmpty, "\(small.sorted())")
    _ = hits
