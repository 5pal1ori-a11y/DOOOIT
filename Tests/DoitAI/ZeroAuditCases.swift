/// 한 대화 묶음을 보내고 답을 모두 돌려줌
@MainActor
func zeroConversation(_ inputs: [String]) async -> [String] {
    let assistant = DoitAssistant.shared
    assistant.reset()
    var replies: [String] = []
    for input in inputs {
        await assistant.send(input)
        replies.append(assistant.messages.last?.text ?? "")
    }
    return replies
}

/// 점검: ZERO_AUDIT 경로가 있으면 모든 대화를 적음
@MainActor
func runZeroAudit(_ sets: [[String]] = zeroAuditSets, file: String? = ProcessInfo.processInfo.environment["ZERO_AUDIT"]) async {
    guard let file, !file.isEmpty else { return }
    var out = ""
    var number = 0
    for inputs in sets {
        let replies = await zeroConversation(inputs)
        number += 1
        out += "### \(number)\n"
        for (q, a) in zip(inputs, replies) {
            out += "Q: \(q)\nA: \(a.replacingOccurrences(of: "\n", with: "\n   "))\n"
        }
        out += "\n"
    }
    try? out.write(toFile: file, atomically: true, encoding: .utf8)
    DoitConversation.userName = nil
}
