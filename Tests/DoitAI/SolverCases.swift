    "버스로 학교까지 30분 걸려"
]

func runSolverCases() {
    func clean(_ s: String) -> String {
        s.replacingOccurrences(of: "−", with: "-").replacingOccurrences(of: " ", with: "")
    }
    /// 기대한 글자가 다른 수의 일부가 아니게 들어 있는지 ("1"이 "−1/2"나 "12" 속에 있는 건 안 침)
    func containsToken(_ answer: String, _ expected: String) -> Bool {
        let a = Array(clean(answer)), e = Array(clean(expected))
        guard !e.isEmpty, e.count <= a.count else { return false }
        let glue: Set<Character> = Set("0123456789./√-^")
        for start in 0...(a.count - e.count) where Array(a[start..<(start + e.count)]) == e {
            let before = start > 0 ? a[start - 1] : nil, after = start + e.count < a.count ? a[start + e.count] : nil
            let digits = Set("0123456789")
            let leftOK = before.map { !glue.contains($0) || !(digits.contains(e.first!) || e.first! == "-" || e.first! == "√") } ?? true
            let rightOK = after.map { !(glue.contains($0) && $0 != "-") || !(digits.contains(e.last!) || e.last! == "π") } ?? true
            if leftOK && rightOK { return true }
        }
        return false
    }
    for c in solverCases {
        let solved = MathSolver.solve(c.question)
        let answer = solved?.answer ?? "(풀지 못함)"
        let ok = solved != nil && c.expect.allSatisfy { containsToken(answer, $0) } && !(solved?.steps.isEmpty ?? true)
        check("문장제 풀이: \(c.question.replacingOccurrences(of: "\n", with: " / "))", ok, "답 \(answer) / 기대 \(c.expect.joined(separator: ", "))")
    }
    for q in solverRefusals {
        let answer = MathSolver.solve(q)?.answer
        check("모르면 풀지 않음: \(q)", answer == nil, "답 \(answer ?? "")")
    }
}
