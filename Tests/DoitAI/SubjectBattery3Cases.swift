func runSubjectBattery3Cases() {
    typealias Stat = (correct: Int, unsolved: Int, wrong: Int, total: Int)
    func runList(_ list: [SB3], tag: String) -> (byArea: [String: Stat], byBroad: [String: Stat], wrongs: [String], unsolved: [String]) {
        var byArea: [String: Stat] = [:], byBroad: [String: Stat] = [:]
        var wrongs: [String] = [], unsolvedList: [String] = []
        for item in list {
            let scan = DoitProblemScan.scan(item.text, math: false)
            let choices = scan.choices
            let label = "[\(item.area)] " + item.text.replacingOccurrences(of: "\n", with: " / ")
            var a = byArea[item.area] ?? (0, 0, 0, 0), b = byBroad[item.broad] ?? (0, 0, 0, 0)
            a.total += 1; b.total += 1
            let detected = DoitSubjectDetector.detect(item.text)?.broad
            guard let solution = DoitSubjectSolve.solve(text: item.text, choices: choices, subjectBroad: detected ?? item.broad,
                                                        body: scan.body, boxItems: scan.boxItems) else {
                a.unsolved += 1; b.unsolved += 1
                byArea[item.area] = a; byBroad[item.broad] = b
                unsolvedList.append(label)
                continue
            }
            let answer = solution.finalAnswer
            let right = choices.count >= 2
                ? (DoitGrader.choiceNumber(answer, choices: choices).map { "\($0)" == item.answer } ?? false)
                : subjectMatches(answer, expected: item.answer)
            check("\(tag) 확인된 답: \(label)", solution.source == DoitAutoSolve.engineSource && !solution.steps.isEmpty, "source \(solution.source ?? "-")")
            if right { a.correct += 1; b.correct += 1 } else { a.wrong += 1; b.wrong += 1; wrongs.append("\(label) → 답 '\(answer)', 정답 '\(item.answer)'") }
            check("\(tag) 오답 없음: \(label)", right, "답 '\(answer)', 정답 '\(item.answer)'")
            byArea[item.area] = a; byBroad[item.broad] = b
        }
        return (byArea, byBroad, wrongs, unsolvedList)
    }
    func line(_ s: Stat) -> String { "정답 \(s.correct) / 전체 \(s.total), 못 풂 \(s.unsolved), 오답 \(s.wrong)" }
    func sum(_ d: [String: Stat]) -> Stat { d.values.reduce((0, 0, 0, 0)) { ($0.0 + $1.correct, $0.1 + $1.unsolved, $0.2 + $1.wrong, $0.3 + $1.total) } }

    let main = runList(subjectBattery3, tag: "과목 배터리3")
    var trapSolved: [String] = []
    for trap in subjectBattery3Traps {
        let scan = DoitProblemScan.scan(trap.text, math: false)
        let solved = DoitSubjectSolve.solve(text: trap.text, choices: scan.choices, subjectBroad: trap.broad, body: scan.body, boxItems: scan.boxItems)
        if let solved { trapSolved.append("\(trap.text.prefix(50).replacingOccurrences(of: "\n", with: " / ")) → '\(solved.finalAnswer)'") }
        check("과목 배터리3 함정은 풀지 않음: \(trap.text.prefix(40))", solved == nil, "답 '\(solved?.finalAnswer ?? "")'")
    }
    check("과목 배터리3: 400문제 이상", subjectBattery3.count >= 400, "\(subjectBattery3.count)문제")
    check("과목 배터리3: 함정 50개 이상", subjectBattery3Traps.count >= 50, "\(subjectBattery3Traps.count)개")
    check("과목 배터리3: 오답 0개", main.wrongs.isEmpty, "오답 \(main.wrongs.count)개")
    for broad in ["과학", "사회", "윤리", "역사", "국어"] {
        guard let s = main.byBroad[broad] else { continue }
        print("과목 배터리3 [\(broad)]: " + line(s))
    }
    for area in main.byArea.keys.sorted() { print("  과목 배터리3 단원 [\(area)]: " + line(main.byArea[area]!)) }
    let total = sum(main.byBroad)
    print("과목 배터리3: " + line(total) + ", 함정 \(subjectBattery3Traps.count)개 중 푼 것 \(trapSolved.count)개")
    for w in main.wrongs { print("  ✗ 오답: " + w) }
    for t in trapSolved { print("  ✗ 함정을 풂: " + t) }
    for u in main.unsolved { print("  · 못 풂: " + u) }
    // 새 문제
    let fresh = runList(subjectBattery3Fresh, tag: "과목 배터리3 새 문제")
    for broad in ["과학", "사회", "윤리", "역사", "국어"] {
        guard let s = fresh.byBroad[broad] else { continue }
        print("과목 배터리3 새 문제 [\(broad)]: " + line(s))
    }
    print("과목 배터리3 새 문제: " + line(sum(fresh.byBroad)))
    for w in fresh.wrongs { print("  ✗ 새 문제 오답: " + w) }
    for u in fresh.unsolved { print("  · 새 문제 못 풂: " + u) }
    let fresh2 = runList(subjectBattery3Fresh2, tag: "과목 배터리3 새 문제 2")
    print("과목 배터리3 새 문제 2: " + line(sum(fresh2.byBroad)))
    for w in fresh2.wrongs { print("  ✗ 새 문제 2 오답: " + w) }
    for u in fresh2.unsolved { print("  · 새 문제 2 못 풂: " + u) }
    runSubjectFactTableCases()
}

